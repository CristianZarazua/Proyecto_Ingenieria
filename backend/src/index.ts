import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import { pool } from './config/db.js';
import authRoutes from './routes/auth.routes.js';
import adminRoutes from './routes/admin.routes.js';
import planesRoutes from './routes/planes.routes.js';
import borradoresRoutes from './routes/borradores.routes.js';
import seguimientoRoutes from './routes/seguimiento.routes.js';
import reportesRoutes from './routes/reportes.routes.js';
dotenv.config();
const app = express();
app.use(cors({ origin: process.env.FRONTEND_URL || 'http://localhost:3000' }));
app.use(express.json());
app.get('/api/health', async (_req, res) => { try { await pool.query('SELECT 1'); res.json({ ok: true, db: 'conectada' }); } catch { res.status(500).json({ ok: false, db: 'sin conexion' }); } });
app.use('/api/auth', authRoutes);
app.use('/api', adminRoutes);
app.use('/api/planes', planesRoutes);
app.use('/api/borradores', borradoresRoutes);
app.use('/api/seguimiento', seguimientoRoutes);
app.use('/api/reportes', reportesRoutes);
const port = Number(process.env.PORT) || 3001;
const host = process.env.HOST || '127.0.0.1';
app.listen(port, host, () => console.log(`API lista en ${host}:${port}`));
